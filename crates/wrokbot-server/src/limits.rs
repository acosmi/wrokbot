//! 输入大小限制 —— v3 §5.2 点名的 transport 四件事之一。
//!
//! # 为什么 G1 就要有它，尽管两条路由都是 GET
//!
//! §5.2 把「输入大小限制」写进 transport 的**构造**，不是写进某条路由的实现。等到第一个
//! POST 出现再补，等于把这条约束的生效时刻交给"下一个人记不记得"。而漏掉它的后果不是
//! 少一个校验，是**没有任何东西挡住一个无限长的请求体**：Axum 的 body 会一直读下去，
//! 内存由对端决定。
//!
//! 把它放在 router 的最外层（见 [`crate::http::router`]），意味着以后每一条新路由**默认
//! 被保护**，作者不需要记得任何事。这是"默认安全"与"记得加"的区别。

/// 请求体上限（字节）。
///
/// **1 MiB。** 取值理由：
///
/// - G1 的两条路由都是 GET，**任何** body 都是多余的，1 MiB 已经宽到不会误伤。
/// - 台账里紧随其后的写路由（`api-channels-activity-post`、thread mint 等）都是小 JSON
///   命令：`AppCommand` 是封闭 enum，最大的载荷是一段 message 文本，离 1 MiB 很远。
/// - 真正的大载荷（AG-UI 附件、截图、文件上传）属于 G4/G5，它们**必须各自声明自己的
///   上限**，而不是把全局上限抬到迁就最大的那一条。理由与 §17.2 的 scope 思路一致：
///   一个为最宽用例设定的全局值，等于对其余所有路由取消了这条防线。
/// - 与 Axum 的默认值（2 MiB）刻意不同：这个数字是本项目**显式选的**，不是继承来的。
///   [`crate::http::router`] 同时关掉了 Axum 的默认限制，让这里成为唯一真源 ——
///   两个上限就是两个答案，排障时没人说得清哪个先命中。
///
/// 改这个值是一次行为变更（客户端会开始收到 413），要随 ledger 条目一起改。
pub const REQUEST_BODY_LIMIT_BYTES: usize = 1024 * 1024;

#[cfg(test)]
mod tests {
    use super::*;

    /// 常量就是文档里写的那个数 —— 防止有人改了值忘了改注释里的"1 MiB"。
    #[test]
    fn limit_is_one_mebibyte() {
        assert_eq!(REQUEST_BODY_LIMIT_BYTES, 1_048_576);
    }
}
